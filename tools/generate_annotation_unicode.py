"""Freeze Python 3.12/UCD 15 scanner properties and IPS-domain NFD/casing.

No general-purpose normalizer is shipped: a cluster is accepted only if its
first scalar decomposes to ASCII plus permitted marks and every subsequent
scalar decomposes solely to permitted marks. Reordering cannot change this
predicate. Original clusters, not their decompositions, are cased and emitted.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import sys
import unicodedata as ucd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_query_case import ROOT, artifact_path, identity, inputs, persist, require
from generate_query_vectors import string


MARKS = frozenset("\u0300\u0302\u0303\u0304\u0305\u0307\u030a\u0323")


def source():
    baseline, fingerprints, provenance, _ = inputs()
    path = Path(baseline["installed"]["package"]) / "annotation.py"
    annotation = identity(path.read_bytes())
    require(annotation == baseline["fingerprints"]["modules"]["annotation.py"],
            "Installed annotation.py changed")
    fingerprints["annotation"] = annotation
    fingerprints["generator"] = identity(Path(__file__).read_bytes())
    provenance["installed_annotation"] = {"path": str(path), **annotation}
    return fingerprints, provenance


def generate():
    before, provenance = source()
    from lingose import annotation
    require(annotation._MARKS == MARKS, "Annotation mark contract changed")
    ranges, bases, marks = [], [], []
    digest = hashlib.sha256()
    for codepoint in range(0x110000):
        if 0xD800 <= codepoint <= 0xDFFF:
            continue
        char = chr(codepoint)
        flags = int(char.isalnum()) | (int(char.isalpha()) << 1) | (int(ucd.category(char).startswith("M")) << 2)
        if flags:
            if ranges and ranges[-1][1] + 1 == codepoint and ranges[-1][2] == flags:
                ranges[-1] = (ranges[-1][0], codepoint, flags)
            else:
                ranges.append((codepoint, codepoint, flags))
        nfd = ucd.normalize("NFD", char)
        base = ord(nfd[0].lower()) if nfd[0].isascii() and nfd[0].isalpha() and all(c in MARKS for c in nfd[1:]) else 0
        mark = all(c in MARKS for c in nfd)
        if base:
            bases.append((codepoint, base, char.lower(), char.upper()))
        if mark:
            marks.append(codepoint)
        digest.update(struct.pack("<IBBB", codepoint, flags, base, mark))
        if base:
            for value in (char.lower(), char.upper()):
                encoded = value.encode("utf-8")
                digest.update(struct.pack("<I", len(encoded)))
                digest.update(encoded)
    # Accepted mark decompositions are nonempty and remain category M with
    # identity casing, so casing just the initial scalar equals str.upper/lower.
    require(all(ucd.category(chr(cp)).startswith("M") and chr(cp).lower() == chr(cp).upper() == chr(cp)
                for cp in marks), "Accepted mark domain needs full cluster casing")
    lines = ["//! Generated by tools/generate_annotation_unicode.py; do not edit.",
             "//! CPython 3.12.4 / Unicode 15.0; Unicode License V3.", "",
             "pub(super) const FLAGS: &[(u32, u32, u8)] = &["]
    lines += [f"    (0x{start:X}, 0x{end:X}, {flags})," for start, end, flags in ranges]
    lines += ["];", "", "pub(super) const BASES: &[(u32, u8, &str, &str)] = &["]
    lines += [f"    (0x{cp:X}, {base}, {string(lower)}, {string(upper)})," for cp, base, lower, upper in bases]
    lines += ["];", "", "pub(super) const MARKS: &[u32] = &[" + ", ".join(f"0x{cp:X}" for cp in marks) + "];",
              "", "pub(super) const SPECIAL: &[(&str, u8, &str, &str)] = &["]
    for cluster in sorted(set(annotation._DOUBLE_BASE) | set(annotation._TO_UPPER) | set(annotation._TO_LOWER)):
        base = annotation._base(cluster)
        lower = annotation._TO_LOWER.get(cluster, cluster.lower())
        upper = annotation._TO_UPPER.get(cluster, cluster.upper())
        lines.append(f"    ({string(cluster)}, {ord(base)}, {string(lower)}, {string(upper)}),")
    lines += ["];", "", "#[cfg(test)]", f'pub(super) const SCALAR_SHA256: &str = "{digest.hexdigest()}";', ""]
    formatted = subprocess.run(["rustfmt", "--edition", "2024", "--emit", "stdout"], input="\n".join(lines),
                               text=True, encoding="utf-8", capture_output=True, check=True)
    tables = formatted.stdout.replace("\r\n", "\n").encode("utf-8")
    report = {"format_version": 1, "unicode_version": ucd.unidata_version,
              "generator": {"path": "tools/generate_annotation_unicode.py", **before["generator"]},
              "provenance": provenance, "counts": {"scalars": 0x110000 - 0x800,
                  "property_ranges": len(ranges), "accepted_base_scalars": len(bases), "accepted_mark_scalars": len(marks)},
              "scalar_sha256": digest.hexdigest(),
              "digest_format": "Ascending scalar: u32 LE codepoint, u8 flags (isalnum=1, isalpha=2, category M=4), u8 accepted NFD ASCII base or zero, u8 accepted NFD-mark predicate; when base nonzero, lower then upper as u32 LE UTF-8 length and UTF-8 bytes",
              "nfd_scope": __doc__, "compiler_unicode": "Never consulted; no Unicode runtime dependency or MSRV change",
              "license": "third_party/unicode/LICENSE.txt",
              "tables": {"path": "src/annotation_unicode_tables.rs", **identity(tables)}}
    require(source()[0] == before, "Generation inputs changed")
    return {"src/annotation_unicode_tables.rs": tables,
            "docs/annotation-unicode.json": (json.dumps(report, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode("utf-8")}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=ROOT)
    args = parser.parse_args()
    output = args.output.resolve()
    require(output == ROOT or output.is_relative_to(ROOT / ".local"), "Output must remain in workspace")
    artifacts = generate()
    persist(output, artifacts, args.write)
    print(json.dumps({"files": {name: identity(artifact_path(name, output).read_bytes()) for name in artifacts},
                      "historical_metadata_preserved": output == ROOT, "inputs_unchanged": True}))


if __name__ == "__main__":
    main()
